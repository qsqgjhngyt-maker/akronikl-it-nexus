// First-party account replaces legacy bearer fallback on the canonical origin.
import assert from 'node:assert/strict';
import {accountClientFixture} from './helpers/account-client-fixture.mjs';
import {accountLocalStorage,lockAccountStorage,verifiedAccount} from '../core/account-storage.js';
import {saveCloudflareSyncConfig,cloudflareSyncStorageKey} from '../sync/cloudflare-config.js';
import {saveIdentityV2SessionCredential} from '../sync/identity-v2-client.js';
import {listCloudProjects,enableProjectCloud,connectCloudAccount,disconnectCloudAccount} from '../sync/cloud-sync.js';
import {createProject,getProject} from '../project-studio/project-store.js';
const f=accountClientFixture('synthetic-session-first');f.verify();
const legacy='nxk_SYNTHETIC_LEGACY_ONLY',session='nxs_'+'SYNTHETIC'.repeat(5);
accountLocalStorage().setItem(cloudflareSyncStorageKey(),JSON.stringify({baseUrl:'https://legacy.invalid',subjectId:f.accountId,token:legacy}));
saveIdentityV2SessionCredential(session);
assert.throws(()=>saveCloudflareSyncConfig({subjectId:'synthetic-other'}),{code:'ACCOUNT_SUBJECT_MISMATCH'});
assert.throws(()=>saveCloudflareSyncConfig({token:legacy}),{code:'SEPARATE_CLOUD_CREDENTIAL_FORBIDDEN'});
let calls=[],mode='ok';
globalThis.fetch=async(url,options={})=>{
 calls.push({url,method:options.method});
 assert.equal(options.credentials,'same-origin');assert.equal(options.headers.authorization,undefined);
 assert.ok(!JSON.stringify(options).includes(legacy));assert.ok(!JSON.stringify(options).includes(session));
 if(mode==='ok')return Response.json({projects:[{id:'session-first-project'}]});
 return Response.json({error:{code:mode==='conflict'?'REVISION_CONFLICT':mode==='expired'?'INVALID_SESSION':'FORBIDDEN',details:{serverRevision:9}}},{status:mode==='conflict'?409:mode==='expired'?401:403});
};
assert.equal((await listCloudProjects())[0].id,'session-first-project');assert.equal(calls.length,1);
for(const op of [()=>connectCloudAccount({baseUrl:'https://legacy.invalid',token:legacy}),disconnectCloudAccount])await assert.rejects(op());
assert.equal(calls.length,1);
mode='forbidden';calls=[];await assert.rejects(listCloudProjects(),e=>e.status===403);assert.equal(calls.length,1);assert.ok(verifiedAccount());
const project=createProject({id:'session-first-conflict',title:'Synthetic conflict'}),before=getProject(project.id).workspace;
mode='conflict';calls=[];await assert.rejects(enableProjectCloud(project.id),e=>e.status===409&&e.code==='REVISION_CONFLICT');
assert.equal(calls.length,1);assert.equal(getProject(project.id).sync.status,'conflict');assert.equal(getProject(project.id).sync.conflict.serverRevision,9);
assert.deepEqual(getProject(project.id).workspace,before);
mode='expired';calls=[];await assert.rejects(listCloudProjects(),e=>e.status===401);assert.equal(calls.length,1);assert.equal(verifiedAccount(),null);
assert.throws(()=>accountLocalStorage(),{code:'VERIFIED_ACCOUNT_REQUIRED'});lockAccountStorage();
console.log('CLOUD_SYNC_SESSION_FIRST_MIGRATION_PASS: cookie priority; 403/409/401 each one request; no fallback');
