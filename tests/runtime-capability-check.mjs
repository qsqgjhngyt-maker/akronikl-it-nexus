import assert from 'node:assert/strict';
import {browserRuntimeProvider as browser} from '../sandbox/providers/browser-runtime.js';
import {analyzeSource,parseRuntimeError} from '../sandbox/diagnostics.js';
const source='#include <iostream>\nclass Device{public:virtual int value(){return 1;}};\nint main(){Device d;std::cout<<d.value();return 0;}';
const assessment=browser.inspect(source);
assert.equal(assessment.support,'unsupported');assert.equal(await browser.available(),false);
assert.deepEqual(browser.capabilities.guaranteed,[]);assert.equal(browser.deprecated,true);
assert.equal(browser.normalize(source).code,source);
let error;try{await browser.run(source)}catch(e){error=e;}
const limit=parseRuntimeError(error,source,{analysis:analyzeSource(source),locale:'ru'});
assert.equal(limit.kind,'provider-limit');assert.equal(limit.line,null);
const broken='int main(){ const int n=1; n=2; }';
const compiler=new Error('main.cpp:1:28: error: cannot assign to variable with const-qualified type');
compiler.code='WASM_COMPILE_ERROR';compiler.anxPhase='compile';compiler.anxCompilerOutput=compiler.message;
const diag=parseRuntimeError(compiler,broken,{analysis:analyzeSource(broken),locale:'ru'});
assert.equal(diag.kind,'compiler-error');assert.equal(diag.providerLimit,false);assert.equal(diag.line,1);
const stringSource='#include <string>\nint main(){return 0;}';
const legacyError=new Error('1:1 cannot find library: string');
legacyError.anxCapability=assessment;
const legacy=parseRuntimeError(legacyError,stringSource,{analysis:analyzeSource(stringSource),locale:'ru'});
assert.equal(legacy.kind,'provider-limit');assert.equal(legacy.missingStdLibrary,'string');
const typoSource='#include <strng>\nint main(){return 0;}';
const typo=parseRuntimeError(new Error('1:1 cannot find library: strng'),typoSource,{analysis:analyzeSource(typoSource),locale:'ru'});
assert.notEqual(typo.kind,'provider-limit');assert.equal(typo.line,1);
console.log('RUNTIME_CAPABILITY_PASS: retired JSCPP, preserved compiler diagnostics and legacy header classification');
