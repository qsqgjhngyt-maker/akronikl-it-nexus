import fs from 'node:fs';
const root=new URL('../',import.meta.url);
const version=JSON.parse(fs.readFileSync(new URL('version.json',root),'utf8')).version;
const projectVersion=JSON.parse(fs.readFileSync(new URL('project.json',root),'utf8')).version;
const index=fs.readFileSync(new URL('index.html',root),'utf8');
const shell=fs.readFileSync(new URL('nexus-shell.html',root),'utf8');
const candidate=JSON.parse(fs.readFileSync(new URL('release-candidate.json',root),'utf8'));
const app=fs.readFileSync(new URL('core/app.js',root),'utf8');
const sw=fs.readFileSync(new URL('service-worker.js',root),'utf8');
const expected='0.1.7-alpha.2.4.6-ui1a.6';
const assert=(v,m)=>{if(!v)throw new Error(m)};
assert(version===expected,`version.json mismatch: ${version}`);
assert(projectVersion===expected,`project.json mismatch: ${projectVersion}`);
assert(candidate.version===expected,'candidate version mismatch');
assert(shell.includes(`app.css?v=${expected}`),'shell CSS cache-buster version mismatch');
assert(shell.includes(`core/bootstrap.js?v=${expected}`),'shell must enter via authenticated bootstrap');
assert(!shell.includes('src="./releases/'+candidate.assetGeneration+'/core/app.js'),'direct app entry bypass');
assert(shell.includes(`Platform Shell v${expected}`),'boot screen version mismatch');
assert(index.includes('./entry-assets/'+candidate.assetGeneration+'/entry.js'),'public entry generation mismatch');
assert(!index.includes('core/app.js')&&!index.includes('core/bootstrap.js'),'public landing must not load private app');
assert(app.includes(`v${expected}`),'topbar candidate identity mismatch');
assert(app.includes(`Platform Shell v${expected}`),'footer version mismatch');
// Legacy source сохраняется для сравнения и не включается в build. Новая cache policy не утверждена.
assert(sw.includes('akronikl-it-nexus-v0.1.7-alpha.2.4.5'),'historical service worker baseline changed');
console.log('RELEASE_VERSION_CONSISTENCY_PASS',version);
